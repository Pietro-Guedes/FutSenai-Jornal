drop function if exists public.get_news_comments(text);
create function public.get_news_comments(p_news_id text default null)
returns table (
  comment_id bigint,
  news_id text,
  user_id uuid,
  nickname text,
  content text,
  created_at timestamptz,
  updated_at timestamptz,
  like_count bigint,
  liked_by_me boolean,
  approved boolean
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_news_id is null and not public.is_news_admin() then
    raise exception 'Somente editores autorizados podem listar todos os comentários.';
  end if;

  return query
  select c.comment_id, c.news_id,
         case when c.user_id = auth.uid() then c.user_id else null::uuid end,
         p.nickname, c.content, c.created_at, c.updated_at,
         (select count(*) from public.news_comment_likes cl
          where cl.comment_id = c.comment_id),
         exists (
           select 1 from public.news_comment_likes cl
           where cl.comment_id = c.comment_id and cl.user_id = auth.uid()
         ),
         c.approved
  from public.news_comments c
  join public.profiles p on p.user_id = c.user_id
  where (p_news_id is null or c.news_id = p_news_id)
    and (c.approved or public.is_news_admin())
  order by c.created_at desc, c.comment_id desc;
end;
$$;

create or replace function public.moderate_news_comment(p_comment_id bigint, p_approved boolean)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  changed_count integer;
begin
  if not public.is_news_admin() then
    raise exception 'Somente editores autorizados podem moderar comentários.';
  end if;
  update public.news_comments
    set approved = p_approved
    where comment_id = p_comment_id;
  get diagnostics changed_count = row_count;
  return changed_count = 1;
end;
$$;

revoke all on function public.moderate_news_comment(bigint, boolean) from public, anon;
grant execute on function public.moderate_news_comment(bigint, boolean) to authenticated;
revoke all on function public.get_news_comments(text) from public, anon;
grant execute on function public.get_news_comments(text) to anon, authenticated;
