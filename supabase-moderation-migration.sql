create table if not exists public.news_reports (
  id bigint generated by default as identity primary key,
  news_id text references public.news(id) on delete cascade,
  comment_id bigint references public.news_comments(comment_id) on delete cascade,
  reporter_user_id uuid references auth.users(id) on delete set null default auth.uid(),
  reason text not null check (char_length(btrim(reason)) between 3 and 500),
  created_at timestamptz not null default now(),
  status text not null default 'pending' check (status in ('pending','reviewed','dismissed')),
  constraint news_reports_one_target check (
    (news_id is not null and comment_id is null) or
    (news_id is null and comment_id is not null)
  )
);

