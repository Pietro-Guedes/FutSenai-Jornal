create or replace function public.get_interaction_results()
returns jsonb
language sql
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'polls', coalesce((
      select jsonb_agg(jsonb_build_object('id', totals.poll_id, 'counts', totals.counts))
      from (
        select v.poll_id, jsonb_object_agg(v.option, v.total) as counts
        from (
          select pv.poll_id, pv.option, count(*) as total
          from public.poll_votes pv
          join public.polls p on p.id = pv.poll_id and p.active
          group by pv.poll_id, pv.option
        ) v
        group by v.poll_id
      ) totals
    ), '[]'::jsonb),
    'awards', coalesce((
      select jsonb_agg(jsonb_build_object('id', totals.award_id, 'counts', totals.counts))
      from (
        select v.award_id, jsonb_object_agg(v.nominee, v.total) as counts
        from (
          select av.award_id, av.nominee, count(*) as total
          from public.award_votes av
          join public.weekly_awards a on a.id = av.award_id and a.active
          group by av.award_id, av.nominee
        ) v
        group by v.award_id
      ) totals
    ), '[]'::jsonb),
    'leaderboard', coalesce((
      select jsonb_agg(jsonb_build_object(
        'nickname', ranked.nickname,
        'points', ranked.points,
        'predictions', ranked.predictions
      ) order by ranked.points desc, ranked.predictions desc, ranked.nickname)
      from (
        select pr.nickname,
          sum(case
            when p.home_score = m.home_score and p.away_score = m.away_score then 3
            when sign(p.home_score - p.away_score) = sign(m.home_score - m.away_score) then 1
            else 0
          end)::integer as points,
          count(*)::integer as predictions
        from public.predictions p
        join public.matches m on m.id = p.match_id
        join public.profiles pr on pr.user_id = p.account_id
        where m.home_score is not null and p.account_id is not null
        group by pr.user_id, pr.nickname
        order by points desc, predictions desc, pr.nickname
        limit 10
      ) ranked
    ), '[]'::jsonb)
  );
$$;

create or replace function public.get_news_likes()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'news_id', grouped.news_id,
    'nicknames', grouped.nicknames
  ) order by grouped.news_id), '[]'::jsonb)
  from (
    select nl.news_id, jsonb_agg(p.nickname order by lower(p.nickname)) as nicknames
    from public.news_likes nl
    join public.profiles p on p.user_id = nl.user_id
    join public.news n on n.id = nl.news_id
    group by nl.news_id
  ) grouped;
$$;

create or replace function public.get_news_comments(p_news_id text default null)
returns table (
  comment_id bigint,
  news_id text,
  user_id uuid,
  nickname text,
  content text,
  created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_news_id is null and not public.is_news_admin() then
    raise exception 'Somente editores autorizados podem listar todos os comentários.';
  end if;

  return query
  select c.comment_id, c.news_id,
         case when c.user_id = auth.uid() then c.user_id else null::uuid end,
         p.nickname, c.content, c.created_at
  from public.news_comments c
  join public.profiles p on p.user_id = c.user_id
  where p_news_id is null or c.news_id = p_news_id
  order by c.created_at desc, c.comment_id desc;
end;
$$;

