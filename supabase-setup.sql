create or replace function public.censor_offensive_words(p_text text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  censored_text text := p_text;
  offensive_word text;
  offensive_words constant text[] := array[
    'arrombado', 'arrombada', 'babaca', 'bosta', 'buceta', 'cacete',
    'caralho', 'corno', 'corna', 'cu', 'cuzão', 'cuzona', 'desgraça',
    'fodido', 'fodida', 'foder', 'foda', 'fudeu', 'fudido', 'fudida',
    'imbecil', 'idiota', 'merda', 'otário', 'otária', 'porra', 'puta',
    'puto', 'vagabundo', 'vagabunda'
  ];
begin
  if censored_text is null then
    return null;
  end if;

  foreach offensive_word in array offensive_words loop
    censored_text := regexp_replace(
      censored_text,
      '\m' || offensive_word || '\M',
      repeat('#', char_length(offensive_word)),
      'gi'
    );
  end loop;

  return censored_text;
end;
$$;

